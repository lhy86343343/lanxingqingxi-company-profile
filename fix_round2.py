def main():
    files = target_files()
    report = collections.defaultdict(list)
    for f in files:
        html = open(f, encoding='utf-8', errors='ignore').read()
        orig = html
        changed = []
        for old, new, desc in STR_MAP:
            c = html.count(old)
            if c:
                html = html.replace(old, new)
                changed.append(f"{desc} ×{c}")
        if changed and html != orig:
            report[f].extend(changed)
            if not DRY:
                open(f, 'w', encoding='utf-8').write(html)

    print(f"{'[DRY-RUN] ' if DRY else ''}命中文件数: {len(report)}")
    for f in sorted(report):
        print(f"\n{f}:")
        for c in report[f]:
            print(f"   {c}")
    if DRY:
        return

    print("\n===== 校验 =====")
    issues = []
    bad = [
        (r'除垢率不低于 95%(?!（碳酸盐)', '除垢率不低于95%未补表3'),
        (r'Fe³⁺浓度(?:监控|控制在)[^（。；]{0,20}?(?:≤|<)[^（。；]{0,10}mg/L(?!（工艺控制值|, process)', 'Fe³⁺控制值未标注'),
        (r'硅酸盐难溶垢(?!（| \()', '垢型未补硫酸盐'),
    ]
    for f in files:
        html = open(f, encoding='utf-8', errors='ignore').read()
        for pat, desc in bad:
            if re.search(pat, html):
                issues.append((f, desc))
        for m in re.finditer(r'<script type="application/ld\+json">(.*?)</script>', html, flags=re.S):
            try:
                json.loads(m.group(1))
            except Exception as e:
                issues.append((f, f'JSON-LD: {e}'))
    if issues:
        print(f"⚠️ {len(issues)} 个问题:")
        for f, msg in issues[:20]:
            print(f"  {f}: {msg}")
    else:
        print("✅ 校验通过")

if __name__ == '__main__':
    main()

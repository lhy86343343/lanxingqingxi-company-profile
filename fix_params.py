def main():
    files = target_files()
    report = collections.defaultdict(list)

    for f in files:
        html = open(f, encoding='utf-8', errors='ignore').read()
        orig = html
        changed = []
        for pat, new, desc in RE_MAP:
            hits = list(re.finditer(pat, html))
            if hits:
                html = re.sub(pat, new, html)
                changed.append(f"{desc} ×{len(hits)}")
        for old, new, desc in STR_MAP:
            c = html.count(old)
            if c:
                html = html.replace(old, new)
                changed.append(f"{desc} ×{c}")
        if changed and html != orig:
            report[f].extend(changed)
            if not DRY:
                open(f, 'w', encoding='utf-8').write(html)

    print(f"{'[DRY-RUN] ' if DRY else ''}映射命中文件数: {len(report)}")
    for f in sorted(report):
        print(f"\n{f}:")
        for c in report[f]:
            print(f"   {c}")

    if DRY:
        return

    # ===== 执行后全站校验 =====
    print("\n===== 校验 =====")
    issues = []
    bad_patterns = [
        (r'(?<![0-9.])6(?:\.0)?(?!\d)\s?g/\(m²·h\)', '腐蚀速率6残留'),
        (r'36542', '36542残留'),
        (r'26135《高压水射流', '26135错名残留'),
        (r'要求的20g', '20g错乱残留'),
        (r'GB/T 25146-2010 §', '§错误引用残留'),
        (r'应低于50mg/L', 'Cl⁻50残留'),
        (r'缓蚀率[>≥]99%[^，。；]*?(零损伤|确保)', '缓蚀率99承诺残留'),
    ]
    for f in files:
        html = open(f, encoding='utf-8', errors='ignore').read()
        for pat, desc in bad_patterns:
            if re.search(pat, html):
                issues.append((f, desc))
        for m in re.finditer(r'<script type="application/ld\+json">(.*?)</script>', html, flags=re.S):
            try:
                json.loads(m.group(1))
            except Exception as e:
                issues.append((f, f'JSON-LD损坏: {e}'))
    if issues:
        print(f"⚠️ {len(issues)} 个问题:")
        for f, msg in issues[:40]:
            print(f"  {f}: {msg}")
    else:
        print("✅ 无残留旧值，JSON-LD 全部解析通过")

if __name__ == '__main__':
    main()
